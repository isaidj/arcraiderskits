/**
 * Traduce una ubicación individual
 */
export function translateLocation(location: string, lang: Locale = "en"): string {
  const trimmedLocation = location.trim();
  return locationTranslations[trimmedLocation]?.[lang] || trimmedLocation;
}

/**
 * Traduce una cadena de ubicaciones separadas por comas
 */
export function translateLocations(foundIn: string, lang: Locale = "en"): string {
  return foundIn
    .split(",")
    .map((location) => translateLocation(location, lang))
    .join(", ");
}
